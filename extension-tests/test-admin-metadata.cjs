'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.join(__dirname,'..');
const bg=fs.readFileSync(path.join(root,'extension','background.js'),'utf8');
const from=bg.indexOf('const normalized=');
const to=bg.indexOf('async function collectAndSync()',from);
assert.ok(from>=0 && to>from);
const context={};
vm.runInNewContext(bg.slice(from,to)+'\nglobalThis.fns={preferredTitle,visiblePhone};',context,{timeout:1000});
const {preferredTitle,visiblePhone}=context.fns;
assert.equal(preferredTitle('RSCI Students Circle (Official)','Muhammad Umer Farooq, ~AQSA, abdul, Abubakar'), 'RSCI Students Circle (Official)');
assert.equal(preferredTitle('Abdullah','Click here for contact info'),'Abdullah');
assert.equal(preferredTitle('Click here for contact info','Ali Khan'),'Ali Khan');
assert.equal(visiblePhone('Abdullah','Ali'), '');
assert.equal(visiblePhone('+92 300 1234567'), '+923001234567');
const admin=fs.readFileSync(path.join(root,'admin-web','admin.js'),'utf8');
const begin=admin.indexOf('function formatId(');
const finish=admin.indexOf('function showApp(',begin);
assert.ok(begin>=0 && finish>begin);
const ctx={};
vm.runInNewContext("const employees=[{id:2,employee_code:'001',name:'Abdullah'}];\n"+admin.slice(begin,finish)+'\nglobalThis.fns={formatId,employeeLabel};',ctx,{timeout:1000});
assert.equal(ctx.fns.employeeLabel(2),'Abdullah (001)', 'public code vs PostgreSQL numeric PK must be distinct');
assert.equal(ctx.fns.formatId({id:4,employee_code:'EMP-00000004'}),'004');
console.log('PASS chat label source priority, no invented phone numbers, correct public employee IDs');
